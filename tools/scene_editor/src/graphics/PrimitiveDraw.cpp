void PrimitiveDrawList::pushLine(vec2 from, vec2 to, vec4 color)
{
    lineVerts.push_back({ from, color });
    lineVerts.push_back({ to, color });
}

void PrimitiveDrawList::pushQuad(vec2 ll, vec2 ur, vec4 color)
{
    triangleVerts.push_back({ ll, color });
    triangleVerts.push_back({ { ur.x, ll.y }, color });
    triangleVerts.push_back({ ur, color });
    triangleVerts.push_back({ ll, color });
    triangleVerts.push_back({ ur, color });
    triangleVerts.push_back({ { ll.x, ur.y }, color });
}

auto PrimitiveDrawList::getLineVerts() const -> std::span<const internal::Vertex2D>
{
    assert(lineVerts.size() % 2 == 0);
    return lineVerts;
}

auto PrimitiveDrawList::getTriangleVerts() const -> std::span<const internal::Vertex2D>
{
    assert(triangleVerts.size() % 3 == 0);
    return triangleVerts;
}

void PrimitiveDrawList::clear()
{
    lineVerts.clear();
    triangleVerts.clear();
}



PrimitiveRenderer::PrimitiveRenderer(
    trc::Device* _device,
    vk::Format _renderTargetFormat,
    const trc::DeviceMemoryAllocator& alloc)
    :
    device(_device),
    renderTargetFormat(_renderTargetFormat),
    alloc(alloc),
    pipelineLayout(*_device, {}, vk::PushConstantRange{ vk::ShaderStageFlagBits::eVertex, 0, 8 }),
    pipelineBase(trc::buildGraphicsPipeline()
        .setVertexShader({
            reinterpret_cast<const ui32*>(kVertexSpirv),
            reinterpret_cast<const ui32*>(kVertexSpirv + sizeof(kVertexSpirv))
        })
        .setFragmentShader({
            reinterpret_cast<const ui32*>(kFragmentSpirv),
            reinterpret_cast<const ui32*>(kFragmentSpirv + sizeof(kFragmentSpirv))
        })
        .addVertexInputBinding(
            vk::VertexInputBindingDescription{
                0, sizeof(internal::Vertex2D),
                vk::VertexInputRate::eVertex
            },
            {
                vk::VertexInputAttributeDescription{ 0, 0, vk::Format::eR32G32Sfloat, 0 },
                vk::VertexInputAttributeDescription{ 1, 0, vk::Format::eR32G32B32A32Sfloat, 8 },
            }
        )
        .setCullMode(vk::CullModeFlagBits::eNone)
        .setFrontFace(vk::FrontFace::eCounterClockwise)
        .setPolygonMode(vk::PolygonMode::eFill)
        .addColorBlendAttachment(vk::PipelineColorBlendAttachmentState{
            true,
            vk::BlendFactor::eSrcAlpha, vk::BlendFactor::eOneMinusSrcAlpha, vk::BlendOp::eAdd,
            vk::BlendFactor::eZero, vk::BlendFactor::eSrcAlpha, vk::BlendOp::eAdd,
            vk::ColorComponentFlagBits::eR
            | vk::ColorComponentFlagBits::eG
            | vk::ColorComponentFlagBits::eB
            | vk::ColorComponentFlagBits::eA
        })
        .build()
    ),
    linePipeline(trc::buildGraphicsPipeline(pipelineBase)
        .setPrimitiveTopology(vk::PrimitiveTopology::eLineList)
        .build(*device, pipelineLayout, vk::PipelineRenderingCreateInfo{
            0x00,   // view mask
            renderTargetFormat,
            vk::Format::eUndefined,
            vk::Format::eUndefined,
        })
    ),
    trianglePipeline(trc::buildGraphicsPipeline(pipelineBase)
        .setPrimitiveTopology(vk::PrimitiveTopology::eTriangleList)
        .build(*device, pipelineLayout, vk::PipelineRenderingCreateInfo{
            0x00,   // view mask
            renderTargetFormat,
            vk::Format::eUndefined,
            vk::Format::eUndefined,
        })
    ),
    vertexBuffer(
        *device,
        sizeof(internal::Vertex2D),
        vk::BufferUsageFlagBits::eVertexBuffer,
        vk::MemoryPropertyFlagBits::eHostVisible | vk::MemoryPropertyFlagBits::eDeviceLocal,
        alloc
    )
{
}

void PrimitiveRenderer::draw(
    const PrimitiveDrawList& drawList,
    trc::Frame& frame,
    trc::RenderStage stage,
    const trc::Viewport& vp)
{
    auto drawCmds = uploadDrawData(drawList);

    frame.spawnTask(
        stage,
        [vp, drawCmds](vk::CommandBuffer cmdBuf, trc::DeviceExecutionContext& ctx)
        {
            vk::RenderingAttachmentInfo colorAttachment{
                vp.target.imageView,
                vk::ImageLayout::eColorAttachmentOptimal,
                vk::ResolveModeFlagBits::eNone, VK_NULL_HANDLE, vk::ImageLayout::eUndefined,
                vk::AttachmentLoadOp::eLoad,
                vk::AttachmentStoreOp::eStore,
                vk::ClearValue{},
            };
            cmdBuf.beginRendering(vk::RenderingInfo{
                vk::RenderingFlags{},
                vp.area.toRect2D(),
                1,        // layer count
                0x00,     // view mask
                colorAttachment,
                nullptr,  // depth attachment
                nullptr,  // stencil attachment
            });

            for (auto& draw : drawCmds)
            {
                if (draw.numVertices == 0) continue;

                draw.pipeline.bind(cmdBuf, ctx.resources());

                const vec2 off = vec2(vp.area.offset);
                const vec2 size = vec2(vp.area.size);
                cmdBuf.setViewport(0, vk::Viewport{ off.x, off.y, size.x, size.y, 0.0f, 1.0f });
                cmdBuf.setScissor(0, vp.area.toRect2D());

                cmdBuf.pushConstants<vec2>(
                    *draw.pipeline.getLayout(), vk::ShaderStageFlagBits::eVertex,
                    0, size);
                cmdBuf.bindVertexBuffers(0, draw.vertexBuffer, draw.vertexBufferOffset);
                cmdBuf.draw(draw.numVertices, 1, 0, 0);

                ctx.deps().access(trc::BufferAccess{
                    draw.vertexBuffer,
                    draw.vertexBufferOffset,
                    draw.numVertices * sizeof(internal::Vertex2D),
                    vk::PipelineStageFlagBits2::eVertexAttributeInput,
                    vk::AccessFlagBits2::eVertexAttributeRead,
                });
            }

            cmdBuf.endRendering();
        }
    );
}

auto PrimitiveRenderer::uploadDrawData(const PrimitiveDrawList& drawList)
    -> std::vector<DrawCommand>
{
    const auto lineVerts = drawList.getLineVerts();
    const auto triVerts = drawList.getTriangleVerts();
    const size_t lineBytes = sizeof(internal::Vertex2D) * lineVerts.size();
    const size_t triBytes = sizeof(internal::Vertex2D) * triVerts.size();

    if (vertexBuffer.size() < lineBytes + triBytes)
    {
        vertexBuffer = trc::Buffer{
            *device,
            lineBytes + triBytes,
            vk::BufferUsageFlagBits::eVertexBuffer,
            vk::MemoryPropertyFlagBits::eHostVisible | vk::MemoryPropertyFlagBits::eDeviceLocal,
            alloc
        };
    }

    auto buf = vertexBuffer.map<ui8*>();
    memcpy(buf,             lineVerts.data(), lineBytes);
    memcpy(buf + lineBytes, triVerts.data(), triBytes);
    vertexBuffer.flush();
    vertexBuffer.unmap();

    return {
        { linePipeline,     *vertexBuffer, 0,         lineVerts.size() },
        { trianglePipeline, *vertexBuffer, lineBytes, triVerts.size() },
    };
}
